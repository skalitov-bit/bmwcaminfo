'use strict';
const assert=require('assert'),path=require('path');
const root=process.argv[2]||path.join(__dirname,'../apps/aurelm_speed_camera_warning');
const {MapPosition,project}=require(path.join(root,'map-projection'));
const {usable}=require(path.join(root,'gps-quality'));
const map=new MapPosition(),now=10000,area={x:266,y:74,w:850,h:398};
const first={lat:55.79,lon:37.55,headingDeg:315,speedKmh:50,accuracyM:5,timeMs:now};
assert.equal(map.position,null,'cold start must not invent a vehicle point');
map.update(first,now);const saved=Object.assign({},map.position);
const road=project(55.791,37.551,map.position,.36,area,map.heading,true);
map.update(null,now+5000);
assert.deepStrictEqual(map.position,saved);assert.equal(map.heading,315);
assert.deepStrictEqual(project(55.791,37.551,map.position,.36,area,map.heading,true),road,'road must not move or rotate on loss');
assert(!usable(first,now+5000),'retained coordinates must remain stale for monitoring');
for(const bad of [Object.assign({},first,{lat:56,accuracyM:100,timeMs:now+5000}),Object.assign({},first,{lat:NaN,timeMs:now+5000}),first])map.update(bad,now+5000);
assert.deepStrictEqual(map.position,saved,'bad/stale samples must not move the map');
map.update(null,now+600000);assert.deepStrictEqual(map.position,saved,'long loss has no display timeout');
const recovered=Object.assign({},first,{lat:55.792,lon:37.553,headingDeg:320,timeMs:now+600000});
map.update(recovered,recovered.timeMs);assert.equal(map.position.lat,recovered.lat);assert.equal(map.heading,320);assert(usable(recovered,recovered.timeMs));
const native=Object.assign({},recovered,{lat:55.793,timeMs:recovered.timeMs+1000,coordinatesValid:true,accuracyM:null,accuracySource:'not_reported',positionSource:'nav',source:'BMW Navigation'});
map.update(native,native.timeMs);assert.equal(map.position.lat,native.lat);map.update(null,native.timeMs+5000);assert.equal(map.position.lat,native.lat);
assert.deepStrictEqual(first,{lat:55.79,lon:37.55,headingDeg:315,speedKmh:50,accuracyM:5,timeMs:now},'input fix is not changed');
console.log('PASS map position: no fabricated cold-start point, loss/freeze, stale and unreliable rejection, heading preservation, recovery, BMW navigation');
